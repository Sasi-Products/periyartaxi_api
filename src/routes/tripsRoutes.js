import express from 'express';
import rateLimit from "express-rate-limit";
import * as c from "../controllers/tripsController.js";
import * as ev from "../controllers/rideEvidenceController.js";
import { auth, role, adminOnly } from "../middleware/auth.js";
const startLimit=rateLimit({windowMs:15*60*1000,limit:12,standardHeaders:'draft-7',legacyHeaders:false});const r=express.Router();
r.use(auth);
r.post('/quote',role('CUSTOMER','ADMIN'),(req,res,next)=>req.user.role==='ADMIN'?adminOnly('trips.manage')(req,res,next):next(),c.quote);
r.get('/offers',role('DRIVER'),c.offers);
r.get('/',role('CUSTOMER','ADMIN','DRIVER'),(req,res,next)=>req.user.role==='ADMIN'?adminOnly('trips.view')(req,res,next):next(),c.list);
r.post('/',role('CUSTOMER','ADMIN'),(req,res,next)=>req.user.role==='ADMIN'?adminOnly('trips.manage')(req,res,next):next(),c.create);
r.get('/:id/timing',role('CUSTOMER','ADMIN','DRIVER'),ev.timing);
r.post('/:id/otp/request',startLimit,role('CUSTOMER','ADMIN','DRIVER'),ev.requestOtp);
r.post('/:id/gps',role('DRIVER'),ev.gps);
r.post('/:id/wait/start',role('DRIVER','ADMIN'),ev.beginWait);
r.post('/:id/wait/end',role('DRIVER','ADMIN'),ev.endWait);
r.post('/:id/distance/verify',adminOnly('trips.override'),ev.verifyDistance);
r.post('/:id/wait/manual',adminOnly('trips.override'),ev.manualWait);
r.post('/:id/wait/:waitId/review',adminOnly('trips.override'),ev.reviewWait);
r.get('/:id',role('CUSTOMER','ADMIN','DRIVER'),(req,res,next)=>req.user.role==='ADMIN'?adminOnly('trips.view')(req,res,next):next(),c.one);
r.post('/:id/offer',role('DRIVER'),c.offerResponse);
r.post('/:id/assign',adminOnly('trips.dispatch'),c.manualAssign);
r.post('/:id/redispatch',adminOnly('trips.dispatch'),c.redispatch);
r.post('/:id/arrive',role('DRIVER','ADMIN'),(req,res,next)=>req.user.role==='ADMIN'?adminOnly('trips.override')(req,res,next):next(),c.arrive);
r.post('/:id/start',startLimit,role('DRIVER','ADMIN'),(req,res,next)=>req.user.role==='ADMIN'?adminOnly('trips.override')(req,res,next):next(),c.start);
r.post('/:id/finish',role('DRIVER','ADMIN'),(req,res,next)=>req.user.role==='ADMIN'?adminOnly('trips.override')(req,res,next):next(),c.finish);
r.post('/:id/cancel',role('CUSTOMER','ADMIN'),(req,res,next)=>req.user.role==='ADMIN'?adminOnly('trips.manage')(req,res,next):next(),c.cancel);
r.post('/:id/charges',role('DRIVER','ADMIN'),(req,res,next)=>req.user.role==='ADMIN'?adminOnly('trips.charges')(req,res,next):next(),c.charges);
r.post('/charges/:chargeId/review',adminOnly('trips.charges'),c.approveCharge);
export default r;

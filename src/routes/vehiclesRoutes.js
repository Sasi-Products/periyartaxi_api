import express from 'express';
import * as c from '../controllers/vehiclesController.js';
import { vehicleMediaUpload } from '../services/vehicleFiles.js';
import { auth, adminOnly } from '../middleware/auth.js';
const router = express.Router();
router.use(auth, adminOnly('vehicles.manage'));
router.get('/', c.list);
router.post('/', c.add);
router.get('/:id', c.get);
router.patch('/:id', c.update);
router.post('/:id/verify', c.verify);
router.get('/:id/media/:group/:key', c.readMedia);
router.post('/:id/media/:group/:key', (req, res, next) => vehicleMediaUpload(req, res, error => error ? next(error) : next()), c.uploadMedia);
router.get('/:id/odometer', c.odometerHistory);
router.post('/:id/odometer', c.addOdometer);
router.get('/:id/services', c.serviceHistory);
router.post('/:id/services', c.addService);
router.post('/:id/services/:logId/invoice', (req, res, next) => vehicleMediaUpload(req, res, error => error ? next(error) : next()), c.uploadServiceInvoice);
router.get('/:id/services/:logId/invoice', c.readServiceInvoice);
export default router;

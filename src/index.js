import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import SequelizePkg from 'sequelize';
import { webhook } from './controllers/paymentsController.js';
import authRoutes from './routes/authRoutes.js';
import usersRoutes from './routes/usersRoutes.js';
import customersRoutes from './routes/customersRoutes.js';
import branchesRoutes from './routes/branchesRoutes.js';
import pricingRoutes from './routes/pricingRoutes.js';
import vehiclesRoutes from './routes/vehiclesRoutes.js';
import driversRoutes from './routes/driversRoutes.js';
import assignmentsRoutes from './routes/assignmentsRoutes.js';
import locationRoutes from './routes/locationRoutes.js';
import telematicsRoutes from './routes/telematicsRoutes.js';
import tripsRoutes from './routes/tripsRoutes.js';
import paymentsRoutes from './routes/paymentsRoutes.js';
import attendanceRoutes from './routes/attendanceRoutes.js';
import payrollRoutes from './routes/payrollRoutes.js';
import expensesRoutes from './routes/expensesRoutes.js';
import analyticsRoutes from './routes/analyticsRoutes.js';
import notificationsRoutes from './routes/notificationsRoutes.js';
import placesRoutes from './routes/placesRoutes.js';
import reviewsRoutes from './routes/reviewsRoutes.js';
import auditRoutes from './routes/auditRoutes.js';
import uploadsRoutes from './routes/uploadsRoutes.js';
const {UniqueConstraintError,ValidationError,ForeignKeyConstraintError}=SequelizePkg;
const app=express();app.disable('x-powered-by');app.set('trust proxy',process.env.NODE_ENV==='production'?1:false);
const allowed=(process.env.CORS_ORIGINS||'http://localhost:5173').split(',').map(x=>x.trim());
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
app.use(cors({origin:(origin,cb)=>!origin||allowed.includes(origin)?cb(null,true):cb(new Error('CORS origin blocked'))}));
app.post('/api/payments/webhook',express.raw({type:'application/json',limit:'500kb'}),webhook);
app.use(express.json({limit:'1mb'}));app.get('/api/health',(_req,res)=>res.json({status:'ok',app:'Periyar Taxi API'}));
app.use('/api/auth', authRoutes);
app.use('/api/users', usersRoutes);
app.use('/api/customers', customersRoutes);
app.use('/api/branches', branchesRoutes);
app.use('/api/pricing', pricingRoutes);
app.use('/api/vehicles', vehiclesRoutes);
app.use('/api/drivers', driversRoutes);
app.use('/api/assignments', assignmentsRoutes);
app.use('/api/locations', locationRoutes);
app.use('/api/telematics', telematicsRoutes);
app.use('/api/trips', tripsRoutes);
app.use('/api/payments', paymentsRoutes);
app.use('/api/attendance', attendanceRoutes);
app.use('/api/payroll', payrollRoutes);
app.use('/api/expenses', expensesRoutes);
app.use('/api/analytics', analyticsRoutes);
app.use('/api/notifications', notificationsRoutes);
app.use('/api/places', placesRoutes);
app.use('/api/reviews', reviewsRoutes);
app.use('/api/audit', auditRoutes);
app.use('/api/uploads', uploadsRoutes);
app.use((req,res)=>res.status(404).json({error:'Route not found',path:req.path}));
app.use((err,req,res,next)=>{
 let status=err.status||500,message=err.message||'Unknown error';if(err instanceof UniqueConstraintError){status=409;message='A record with this unique value already exists'}if(err instanceof ValidationError){status=422;message=err.errors?.map(x=>x.message).join('; ')||message}if(err instanceof ForeignKeyConstraintError){status=422;message='Referenced record not found'}if(err.name==='MulterError'){status=400;message=err.message}if(message==='CORS origin blocked')status=403;
 if(status>=500)console.error('[API ERROR]',err.stack||err);res.status(status).json({error:status>=500?'Server error':message,code:err.code||undefined})});
export default app;
